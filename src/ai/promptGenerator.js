function generateSecondRoundPrompt({
  presentingProblemId,
  age,
  sex,
  weightKg,
  heightCm,
  otherSymptomsText,
  round1QuestionsAsked = [],
  round1Responses = [],
  patientHistory = [],
  medicalHistory,
}) {
  if (!presentingProblemId || typeof age !== 'number' || !sex) {
    throw new Error('generateSecondRoundPrompt: ورودی ناقص — presentingProblemId, age, sex الزامی هستند.');
  }

  const round1QaLines = round1QuestionsAsked
    .map((q, i) => `س${i + 1}: ${q}\nج${i + 1}: ${round1Responses[i] ?? '(پاسخ داده نشده)'}`)
    .join('\n');

  const narrativeIntro = buildPatientNarrativeIntro({
    age,
    sex,
    weightKg,
    heightCm,
    presentingProblemId,
    otherSymptomsText,
    patientHistory,
  });
  const medicalHistoryText = formatMedicalHistory(medicalHistory);

  const userContent = `
${narrativeIntro}

سؤالات و پاسخ‌های دور اول (این ۵ سؤال دیگر تکرار نشوند؛ پاسخ‌ها را واقعاً برای تصمیم بین escalate یا ادامه لحاظ کن):
${round1QaLines}

${medicalHistoryText}

بر اساس این اطلاعات، طبق فرمت خواسته‌شده در دستورالعمل سیستم، یکی از دو حالت escalate:false (با ۵ سؤال جدید) یا escalate:true (با تصمیم نهایی) را پاسخ بده.
`.trim();

  console.log('[BUILD_TAG round2-diagnostic-2026-07-30-A] generateSecondRoundPrompt در حال اجراست.');
  console.log(
    `generateSecondRoundPrompt: round1Responses.length=${round1Responses.length} | مقادیر: ${JSON.stringify(round1Responses)}`
  );
  console.log('generateSecondRoundPrompt: متن کامل بخش سؤال‌وپاسخ دور اول که به AI فرستاده می‌شود:\n' + round1QaLines);
  console.log('generateSecondRoundPrompt: متن کامل prompt.user که به AI فرستاده می‌شود:\n' + userContent);

  return {
    system: SECOND_ROUND_SYSTEM_INSTRUCTIONS,
    user: userContent,
  };
}

