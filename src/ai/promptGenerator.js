function generateTriagePrompt({
  presentingProblemId,
  age,
  sex,
  weightKg,
  heightCm,
  otherSymptomsText,
  questionsAsked = [],
  patientResponses = [],
  patientHistory = [],
  medicalHistory,
}) {
  if (!presentingProblemId || typeof age !== 'number' || !sex) {
    throw new Error('generateTriagePrompt: ورودی ناقص — presentingProblemId, age, sex الزامی هستند.');
  }

  const qaLines = questionsAsked
    .map((q, i) => `س${i + 1}: ${q}\nج${i + 1}: ${patientResponses[i] ?? '(پاسخ داده نشده)'}`)
    .join('\n');

  const narrativeIntro = buildPatientNarrativeIntro({
    age,
    sex,
    weightKg,
    heightCm,
    presentingProblemId,
    otherSymptomsText,
    patientHistory,
  });
  const medicalHistoryText = formatMedicalHistory(medicalHistory);

  const userContent = `
${narrativeIntro}

${qaLines ? `سوابق پرسش و پاسخ (این پاسخ‌ها را در تصمیم نهایی واقعاً لحاظ کن، نه صرفاً بازگو):\n${qaLines}` : 'هنوز هیچ سؤال و پاسخی ثبت نشده است.'}

${medicalHistoryText}

بر اساس این اطلاعات، طبق فرمت خواسته‌شده در دستورالعمل سیستم پاسخ بده.
`.trim();

  return {
    system: SYSTEM_INSTRUCTIONS,
    user: userContent,
  };
}

