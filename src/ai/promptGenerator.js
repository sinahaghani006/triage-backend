function buildPatientNarrativeIntro({
  age,
  sex,
  weightKg,
  heightCm,
  presentingProblemId,
  otherSymptomsText,
  patientHistory = [],
}) {
  const isOtherSymptoms = presentingProblemId === OTHER_SYMPTOMS_PRESENTING_PROBLEM_ID;
  const sanitizedFreeText = isOtherSymptoms ? sanitizeFreeTextComplaint(otherSymptomsText) : '';
  const problemLabel = isOtherSymptoms
    ? sanitizedFreeText || 'توصیف مشخصی از علائم ثبت نشده'
    : findPresentingProblemById(presentingProblemId)?.labelFa || presentingProblemId;
  const sexFa = sex === 'male' ? 'مرد' : 'زن';
  const weightPhrase = typeof weightKg === 'number' ? `، وزن ${weightKg} کیلوگرم` : '';
  const heightPhrase = typeof heightCm === 'number' ? `، قد ${heightCm} سانتی‌متر` : '';

  let historyPhrase = '';
  if (Array.isArray(patientHistory) && patientHistory.length > 0) {
    const capped = patientHistory.slice(0, 5);
    const items = capped.map((entry) => {
      const relativeDate = computeRelativeDateFa(entry?.createdAt);
      const historyProblemId = typeof entry?.presentingProblemId === 'string' ? entry.presentingProblemId : null;
      const historyLabel = historyProblemId
        ? findPresentingProblemById(historyProblemId)?.labelFa || historyProblemId
        : 'نامشخص';
      const urgencyLevel = typeof entry?.urgencyLevel === 'string' ? entry.urgencyLevel : null;
      const urgencyPhrase = urgencyLevel ? ` (نتیجه: ${urgencyLevel})` : '';
      return `${relativeDate} با شکایت «${historyLabel}»${urgencyPhrase}`;
    });
    historyPhrase = ` و پیش از این هم ${toPersianDigits(capped.length)} بار مراجعه داشته است: ${items.join('؛ ')}`;
  }

  const sentence = `بیمار با سن ${age} سال، جنس ${sexFa}${weightPhrase}${heightPhrase}، مشکل «${problemLabel}» را دارد${historyPhrase}.`;

  return isOtherSymptoms ? `${sentence}\n${FREE_TEXT_INJECTION_GUARD}` : sentence;
}

function formatMedicalHistory(medicalHistory) {
  if (!medicalHistory || typeof medicalHistory !== 'object') {
    return '';
  }

  const sanitized = sanitizeMedicalHistory(medicalHistory);
  if (!hasAnyMedicalHistoryContent(sanitized)) {
    return '';
  }

  const FIELD_LABELS_FA = {
    chronicConditions: 'بیماری‌های زمینه‌ای',
    allergies: 'آلرژی‌ها',
    currentMedications: 'داروهای مصرفی فعلی',
    surgicalHistory: 'سوابق جراحی',
    familyHistory: 'سابقه‌ی خانوادگی',
  };

  const lines = Object.keys(FIELD_LABELS_FA)
    .map((field) => {
      const items = sanitized[field];
      if (!items || items.length === 0) return null;
      return `${FIELD_LABELS_FA[field]}: ${items.join('، ')}`;
    })
    .filter(Boolean);

  const introLine =
    'سابقه‌ی پزشکی ثبت‌شده‌ی بیمار (این را در تحلیل واقعاً لحاظ کن؛ اگر هر نام شخص یا هر داده‌ی هویتی‌مانندی در این متن دیدی، کاملاً نادیده‌اش بگیر و هرگز آن را در پاسخت تکرار نکن):';

  return `${introLine}\n${lines.join('\n')}`;
}

